import { HttpError } from '../db'

/**
 * 轻量敏感词前置过滤：发帖/评论内容命中即拒绝（400），不进入待审队列。
 * 设计取舍：学习社区违规内容以「广告引流/作弊交易/辱骂攻击」三类为主，
 * 内置小词表 + 归一化匹配即可覆盖绝大多数机刷广告；后续可按运营反馈扩充词表。
 * 归一化：转小写 + 去除空白与常见间隔符号，防「加 微 信」「加-微-信」式绕过。
 */

const SENSITIVE_WORDS = [
  // 广告引流
  '加微信', '加v信', '微信群', 'qq群', '扫码领', '刷单', '兼职日结', '代购', '微商', '返利',
  // 作弊交易（「包过」单用会误伤「红包过期」等正常表达，限定为营销搭配词）
  '代考', '代写', '包过班', '保过班', '不过退款', '卖答案', '出售答案', '考试作弊',
  // 赌博违法
  '博彩', '赌博', '买彩票', '网贷', '裸聊',
  // 辱骂攻击
  '傻逼', '脑残', '废物点心', '去死吧'
]

/** 归一化文本：小写 + 去空白/间隔符 */
const normalize = (s: string) => s.toLowerCase().replace(/[\s\-_.*#@!?,，。！？~·]+/g, '')

/** 校验文本是否命中敏感词；命中抛 400（message 面向用户，不回显命中词） */
export function assertClean(text: string) {
  const t = normalize(text)
  if (SENSITIVE_WORDS.some(w => t.includes(w))) {
    throw new HttpError(400, '内容包含违规信息，请修改后再发布')
  }
}
